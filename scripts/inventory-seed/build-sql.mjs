// node scripts/inventory-seed/build-sql.mjs > supabase/seed/inventory_jmc_2026_11.sql
import * as seed from './jmc-2026-11.mjs'
import { seedMovements } from './movements.mjs'

const UUID_ARRAYS = new Set(['site_ids', 'replaces_ids', 'source_dn_ids'])
const q = (v, colName) => v === null || v === undefined ? 'null'
  : UUID_ARRAYS.has(colName) ? `array[${v.map(x => q(x)).join(',')}]::uuid[]`
  : typeof v === 'number' || typeof v === 'boolean' ? String(v)
  : typeof v === 'object' ? `${q(JSON.stringify(v))}::jsonb`
  : `'${String(v).replace(/'/g, "''")}'`

function insert(table, rows, cols) {
  const vals = rows.map(r => `  (${cols.map(c => typeof c === 'function' ? c(r) : q(r[c], c)).join(', ')})`).join(',\n')
  const names = cols.map(c => typeof c === 'function' ? c.col : c)
  return `insert into public.${table} (${names.join(', ')}) values\n${vals};\n`
}
const col = (name, fn) => Object.assign(fn, { col: name })

const out = []
out.push(`-- Generated by scripts/inventory-seed/build-sql.mjs — do not edit by hand.
-- JMC Wines Group inventory seed (3 Nov 2026). Run once, after 013.
begin;
do $$ begin
  if exists (select 1 from public.inv_clients where doc_ref = '${seed.client.doc_ref}') then
    raise exception 'JMC inventory seed already applied';
  end if;
end $$;
`)
const c = seed.client
out.push(`insert into public.inv_clients (id, customer_id, project_id, doc_ref, quotation_no, contact_name, company, mobile, project_title, notes) values (
  ${q(c.id)}, (select id from public.customers where ${c.customer_lookup} order by created_at limit 1),
  (select id from public.projects where ${c.project_lookup} order by created_at limit 1),
  ${q(c.doc_ref)}, ${q(c.quotation_no)}, ${q(c.contact_name)}, ${q(c.company)}, ${q(c.mobile)}, ${q(c.project_title)}, ${q(c.notes)});
`)
out.push(insert('inv_products', seed.products, ['id', 'sku', 'name', 'invoice_detail', 'dn_name', 'dn_detail', 'dn_components', 'category', 'brand_model', 'unit', 'price', 'kind', 'is_stock', 'is_free', 'track_serials', 'warranty_months', 'warranty_label', 'low_stock_threshold', 'sort_order']))
out.push(insert('inv_locations', seed.locations.map(l => ({ is_outlet: true, sort_order: 0, client_id: null, address: null, manager_name: null, manager_mobile: null, ...l })),
  ['id', 'kind', 'name', 'client_id', 'address', 'manager_name', 'manager_mobile', 'is_outlet', 'sort_order']))

const docs = seed.documents.map(d => ({ total: 0, ...d }))
out.push(insert('inv_documents', docs, ['id', 'client_id', 'type', 'doc_no', 'seq', 'doc_date', 'due_date', 'status', 'title', 'intro', 'site_ids', 'lines', 'meta', 'replaces_ids', 'source_dn_ids', 'total']))
out.push(Object.entries(seed.replacedBy).map(([id, by]) => `update public.inv_documents set replaced_by_id = ${q(by)} where id = ${q(id)};`).join('\n') + '\n')

const { rows } = seedMovements(seed)
out.push(insert('inv_movements', rows.map(r => ({ document_id: null, ...r })), ['moved_on', 'product_id', 'qty', 'from_location_id', 'to_location_id', 'type', 'document_id', 'reference', 'note']))

out.push(insert('inv_payments', seed.payments, ['id', 'client_id', 'invoice_id', 'receipt_id', 'paid_on', 'amount', 'method', 'cheque_no', 'cheque_status', 'software_amount', 'hardware_amount',
  col('pm_invoice_id', p => `(select id from public.invoices where invoice_no = ${q(p.pm_invoice_no)})`)]))
out.push(seed.payments.map(p => `update public.inv_documents set pm_invoice_id = (select id from public.invoices where invoice_no = ${q(p.pm_invoice_no)}), meta = meta || jsonb_build_object('payment_id', ${q(p.id)}::text) where id = ${q(p.receipt_id)};`).join('\n') + '\n')

const sheet = seed.countSheet
out.push(insert('inv_count_sheets', [{
  ...sheet,
  lines: sheet.lines.map(l => ({ label: l.label, product_ids: l.skus.map(s => seed.P[s].id), used: l.used, left: Object.values(l.left).reduce((a, b) => a + b, 0), ...(l.note ? { note: l.note } : {}) }))
}], ['id', 'counted_on', 'location_id', 'lines', 'notes']))

out.push(`insert into public.inv_doc_counters (client_id, type, last_seq) values
  (${q(c.id)}, 'DELIVERY_NOTE', 4), (${q(c.id)}, 'INVOICE', 6), (${q(c.id)}, 'RECEIPT', 3)
on conflict (client_id, type) do update set last_seq = greatest(public.inv_doc_counters.last_seq, excluded.last_seq);

-- status + PM mirror (085-03 → paid; 085-06 → "sent" mirror for the open balance)
select public.inv_refresh_invoice(${q(seed.inv[3].id)});
select public.inv_refresh_invoice(${q(seed.inv[6].id)});
commit;
`)
process.stdout.write(out.join('\n'))
